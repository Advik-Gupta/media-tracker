#!/usr/bin/env node
/* ============================================================
   CENTRALISE - one-time migration to a master film registry.

   Every distinct work becomes a record in assets/js/data/_films.js,
   keyed by normalised title + year (+ season marker for TV). Each
   list then stores only a reference to that key plus its own
   list-specific fields (position, tier, note).

   Two things fall out of this for free:
     - a film in several lists is ONE film, so ticking it anywhere
       ticks it everywhere, with no manual `link` bookkeeping
     - posters are looked up once, in one place
   ============================================================ */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const DATA = path.join(__dirname, "..", "assets/js/data");
const SKIP = new Set(["universes.js", "countries.js", "_films.js"]);
const files = fs
  .readdirSync(DATA)
  .filter((f) => f.endsWith(".js") && !SKIP.has(f));

const ctx = { window: {}, console };
vm.createContext(ctx);
for (const f of files)
  vm.runInContext(fs.readFileSync(path.join(DATA, f), "utf8"), ctx);
const cats = ctx.window.CATALOGUES;

const norm = (s) =>
  String(s)
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/^(the|a|an)\s+/, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
const SEASONISH =
  /season|series|part|episode|vol|chapter|miniseries|final|^s\d/i;

function filmKey(it) {
  const sub = it.sub && SEASONISH.test(it.sub) ? "-" + norm(it.sub) : "";
  return (norm(it.title) + sub + "-" + it.release.slice(0, 4)).replace(
    /\s+/g,
    "-",
  );
}

/* ---------- build the registry ---------- */
const FILMS = {};
const better = (a, b) =>
  b && (!a || String(b).length > String(a).length) ? b : a;

for (const [uni, cat] of Object.entries(cats)) {
  for (const it of cat.items) {
    if (it.alias) continue;
    const k = filmKey(it);
    const poster = cat.posters && cat.posters[it.id];
    const url = !poster
      ? null
      : /^https?:\/\//.test(poster) || poster.startsWith("assets/")
        ? poster
        : cat.imgDir + poster;
    const f = (FILMS[k] ||= { title: it.title, release: it.release });
    if (it.sub && SEASONISH.test(it.sub)) f.sub = it.sub;
    f.title = f.title.length >= it.title.length ? f.title : it.title; // prefer the fuller title
    f.release = f.release < it.release ? f.release : it.release;
    if (!f.poster && url) f.poster = url;
    if ((it.mins || 0) > (f.mins || 0)) f.mins = it.mins;
    if (it.eps) f.eps = it.eps;
    if (it.score) f.score = Math.max(f.score || 0, it.score);
    if (it.type && !f.type) f.type = it.type;
    f.note = better(f.note, it.note);
    (f.in ||= []).push(uni);
  }
}

const q = (s) =>
  "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";

let out = `/* ============================================================
   FILM REGISTRY - the single record for every distinct work.

   Lists do not store films; they store a \`film\` key pointing here.
   That means a title appearing in ten lists is still one film: one
   poster lookup, one watched flag, one place to correct a mistake.

   Keyed by normalised title + year, plus a season marker for TV.
   Generated by build/centralise.js; safe to hand-edit afterwards.
   ============================================================ */

const FILMS = {
`;
for (const k of Object.keys(FILMS).sort()) {
  const f = FILMS[k];
  const bits = [`title: ${q(f.title)}`];
  if (f.sub) bits.push(`sub: ${q(f.sub)}`);
  bits.push(`release: ${q(f.release)}`);
  if (f.mins) bits.push(`mins: ${f.mins}`);
  if (f.eps) bits.push(`eps: ${f.eps}`);
  if (f.score) bits.push(`score: ${f.score}`);
  if (f.type) bits.push(`type: ${q(f.type)}`);
  if (f.poster) bits.push(`poster: ${q(f.poster)}`);
  out += `  ${q(k)}: { ${bits.join(", ")} },\n`;
}
out += `};

/* Merge a list entry with its film record. List fields win for anything
   list-specific (position, tier, era label); the film owns the facts. */
function resolveFilm(entry) {
  const f = FILMS[entry.film] || {};
  return { ...f, ...entry, title: f.title || entry.title, poster: f.poster };
}
`;
fs.writeFileSync(path.join(DATA, "_films.js"), out);
console.log(`_films.js: ${Object.keys(FILMS).length} distinct works`);
console.log(
  `  shared by 2+ lists: ${Object.values(FILMS).filter((f) => new Set(f.in).size > 1).length}`,
);

/* ---------- rewrite each list to reference the registry ---------- */
let rewritten = 0;
for (const f of files) {
  const uni = f.replace(/\.js$/, "");
  const cat = cats[uni];
  if (!cat) continue;
  let src = fs.readFileSync(path.join(DATA, f), "utf8");

  const lines = cat.items
    .filter((it) => !it.alias)
    .map((it) => {
      const bits = [`w: ${it.w}`, `film: ${q(filmKey(it))}`];
      if (it.sub && !SEASONISH.test(it.sub)) bits.push(`sub: ${q(it.sub)}`);
      bits.push(
        `type: ${q(it.type)}`,
        `saga: ${q(it.saga)}`,
        `phase: ${it.phase == null ? "null" : it.phase}`,
        `chrono: ${it.chrono}`,
        `cLabel: ${q(it.cLabel)}`,
        `rel: ${q(it.rel)}`,
      );
      if (it.upcoming) bits.push("upcoming: true");
      const head = `  { ${bits.join(", ")}`;
      return it.note ? `${head},\n    note: ${q(it.note)} },` : `${head} },`;
    });

  const s = src.indexOf("const ITEMS = [");
  const alt = s < 0 ? src.search(/const [A-Z_]+ = \[/) : s;
  const open = src.indexOf("[", alt);
  const close = src.indexOf("\n];", open);
  src = src.slice(0, open + 1) + "\n" + lines.join("\n") + src.slice(close);

  /* posters now live in the registry */
  src = src.replace(/\/\*[^*]*Posters[^*]*\*\/\n/g, "");
  src = src.replace(
    /const POSTERS = \{[\s\S]*?\n\};\n/,
    "const POSTERS = {};   // posters live in _films.js\n",
  );
  src = src.replace(
    /const POSTERS = \{\};\n\[[\s\S]*?\.forEach\(\(id\) => \{ POSTERS\[id\] = id \+ '\.jpg'; \}\);\n/,
    "const POSTERS = {};   // posters live in _films.js\n",
  );
  fs.writeFileSync(path.join(DATA, f), src);
  rewritten += 1;
}
console.log(`rewrote ${rewritten} list files to reference the registry`);
