#!/usr/bin/env node
/* ============================================================
   Resolve a plain list of book titles into real Open Library
   data (cover, author, year) and write it as a built-in book
   collection - the book-vault equivalent of a curated movie
   universe (Nolan, Tarantino, etc).

     node build/import-books.js <file.txt> --id sanderson-cosmere \
       --name "Brandon Sanderson - The Cosmere" --author "Brandon Sanderson"

   The input file is one title per line, in the order you want
   it to display - reading order for a series, say. Blank lines
   are ignored.
   ============================================================ */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "assets/js/data/books");

const arg = (n, d) => {
  const i = process.argv.indexOf(`--${n}`);
  return i > -1 ? process.argv[i + 1] : d;
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function resolveTitle(title, author) {
  const q = author ? `${title} ${author}` : title;
  const fields = "key,title,author_name,cover_i,first_publish_year";
  const url = `https://openlibrary.org/search.json?q=${encodeURIComponent(q)}&fields=${fields}&limit=5`;

  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const r = await fetch(url, {
        headers: { "User-Agent": "MediaVault/1.0 (personal book collections, contact: not-provided)" },
      });
      if (!r.ok) {
        await sleep(1000 * (attempt + 1));
        continue;
      }
      const data = await r.json();
      const docs = data.docs || [];
      if (!docs.length) return null;

      if (author) {
        const surname = author.toLowerCase().split(" ").pop();
        const match = docs.find((d) => (d.author_name || []).some((a) => a.toLowerCase().includes(surname)));
        if (match) return match;
      }
      return docs[0];
    } catch (e) {
      await sleep(1000 * (attempt + 1));
    }
  }
  return null;
}

async function main() {
  const file = process.argv[2];
  const id = arg("id");
  const name = arg("name", id);
  const author = arg("author", "");
  const tagline = arg("tagline", "");

  if (!file || !id) {
    console.error("Usage: node build/import-books.js <file.txt> --id <id> --name <name> [--author <author>] [--tagline <tagline>]");
    process.exit(1);
  }

  const titles = fs
    .readFileSync(file, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);

  console.log(`Resolving ${titles.length} titles for "${name}"...\n`);

  const books = [];
  for (const title of titles) {
    process.stdout.write(`  ${title} ... `);
    const hit = await resolveTitle(title, author);
    if (hit) {
      books.push({
        key: String(hit.key || "").replace(/^\/works\//, ""),
        title: hit.title || title,
        author: (hit.author_name || [])[0] || author || "",
        cover: hit.cover_i || null,
        year: hit.first_publish_year || null,
      });
      console.log("ok" + (hit.cover_i ? "" : " (no cover)"));
    } else {
      books.push({ key: null, title, author, cover: null, year: null });
      console.log("NOT FOUND");
    }
    await sleep(300);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const resolved = books.filter((b) => b.key).length;
  const src =
    `/* Generated by build/import-books.js. Safe to hand-edit afterwards. */\n` +
    `(window.BOOK_COLLECTIONS ||= {})[${JSON.stringify(id)}] = ${JSON.stringify(
      { name, tagline, author, books },
      null,
      2,
    )};\n`;
  fs.writeFileSync(path.join(OUT_DIR, `${id}.js`), src);

  console.log(`\n${resolved}/${books.length} resolved -> assets/js/data/books/${id}.js`);
  const missing = books.filter((b) => !b.key).map((b) => b.title);
  if (missing.length) console.log(`  not found: ${missing.join(", ")}`);
}

main();
